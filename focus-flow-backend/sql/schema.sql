CREATE DATABASE IF NOT EXISTS focus_flow_db;
USE focus_flow_db;

CREATE TABLE IF NOT EXISTS cloud_users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(150) UNIQUE NOT NULL,
  password VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS backups (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  backup_title VARCHAR(255) NOT NULL,
  data_payload MEDIUMTEXT NOT NULL,
  file_size INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_backups_user (user_id),
  FOREIGN KEY (user_id) REFERENCES cloud_users(id) ON DELETE CASCADE
);